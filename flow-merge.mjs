// Send to the base branch, the data half: what a flow's `output` holds about the
// pull request its work becomes (flows.mjs validates it on every write). Pure:
// no file access, no git.
//
//   output.merge = { head, base, title, body, at }   the AGENT's: `flow pr` records the branch,
//                  the base it goes into, a plain-English title and a body that follows the
//                  repo's own pull request template (tools/pr-cli.mjs)
//   output.pr    = { url, number, state, openedAt, checks, checkedAt, error }   the SERVER's: written
//                  only by the send route after the user clicks (pr-routes.mjs), kept by
//                  mergeKeepingAnswers like an answer, so no agent can claim a pull request
//
// ⚠️ A pull request must not credit an AI tool. The title and body are refused when a
// line credits one (`creditOf`, below), and a commit message line that does blocks the send
// (pr-check.mjs).

import { sayShorter } from './flow-story.mjs'

/** A branch name git and the shell can never read as anything else: no `..`, never a leading dash, no `+` or `:`. */
const BRANCH = /^[A-Za-z0-9._/-]{1,100}$/
export const isBranch = v => typeof v === 'string' && BRANCH.test(v) && !v.includes('..') && !v.startsWith('-')
export const BRANCH_RULE = 'a branch name: letters, digits, dots, dashes, underscores and slashes, at most 100, no .., not starting with a dash'
export const MERGE_MAX = Object.freeze({ title: 120, body: 6000 })
export const PR_STATES = Object.freeze(['open', 'merged', 'closed'])
export const CHECKS = Object.freeze(['pending', 'passing', 'failing', 'none'])

const isObject = v => !!v && typeof v === 'object' && !Array.isArray(v)
const isText = v => typeof v === 'string' && v.trim() !== ''
const lines = text => String(text ?? '').split(/\r?\n/).map(l => l.trim()).filter(Boolean)

// ═══ the credit rule: ONE rule for commit messages, the title and the body ═══
//
// A line credits an AI tool when it is
//   - a Co-authored-by: or Signed-off-by: trailer whose name or address names a tool (a person passes);
//   - Generated with / by / using at the start of a line (after an emoji or a > at most), or anywhere on a
//     line that also carries [Claude Code] or the robot emoji;
//   - an authorship phrase naming the tool itself: written, built, authored, created, made or implemented,
//     by or with <tool> (`built with a cursor` is prose, not a credit).
// Nothing else does: a product the work talks about (`The summary is generated by Gemini 3 Flash`), a file
// named after one, the word regenerated.

const TOOL = String.raw`(?:claude|anthropic|copilot|chatgpt|openai|gemini|cursor|codex|devin|aider)`
const NAMES_TOOL = new RegExp(String.raw`\b${TOOL}\b|noreply@anthropic\.com|\[Claude Code\]`, 'i')
const TRAILER = /^(?:co-authored-by|signed-off-by):\s*(.*)$/i
const GENERATED_LEAD = /^(?:>\s*)?(?:[^\p{L}\p{N}\s]{1,4}\s*)?generated (?:with|by|using)\b/iu
const GENERATED = /\bgenerated (?:with|by|using)\b/i
const MARKED = /\[Claude Code\]|\u{1F916}/u
const AUTHORED = new RegExp(String.raw`\b(?:written|built|authored|created|made|implemented) (?:by|with) ${TOOL}\b`, 'i')

/** Why `line` credits an AI tool ('co-author', 'generated' or 'authored'), or null when it does not. */
export function creditOf(line) {
  const l = String(line ?? '').trim()
  const trailer = TRAILER.exec(l)
  if (trailer) return NAMES_TOOL.test(trailer[1]) ? 'co-author' : null
  if (GENERATED_LEAD.test(l) || (GENERATED.test(l) && MARKED.test(l))) return 'generated'
  return AUTHORED.test(l) ? 'authored' : null
}

/** The lines of a commit message that credit an AI tool. */
export const commitCredits = message => lines(message).filter(l => creditOf(l))

/** The first line of a pull request title or body that credits an AI tool, or null. */
export const textCredit = text => lines(text).find(l => creditOf(l)) ?? null

const clip60 = line => (line.length > 60 ? `${line.slice(0, 59)}…` : line)
/** The refusal for a title or body line: names it, and says what to do. */
export const creditProblem = line => `a pull request must not credit an AI tool: "${clip60(line)}": remove this line`
/** The blocker for a commit line: a pushed commit cannot be reworded, so the way out is a new branch. */
export const commitProblem = (sha, line) => `Commit ${sha} "${clip60(line)}": this commit credits an AI tool; it cannot be reworded once pushed, so make a new branch without it`

// ═══ validation ═══

/** The problems of `out.merge` and `out.pr`, in plain words, one line each. */
export function validateSend(out) {
  const problems = []
  const m = out.merge
  if (m !== undefined) {
    if (!isObject(m)) problems.push('output.merge must be a JSON object')
    else {
      for (const key of ['head', 'base']) if (!isBranch(m[key])) problems.push(`output.merge ${key} must be ${BRANCH_RULE}`)
      if (!isText(m.title)) problems.push('output.merge title must say what the pull request does')
      else if (/[\r\n]/.test(m.title)) problems.push('output.merge title must be one line')
      else if (m.title.length > MERGE_MAX.title) problems.push(`output.merge title: ${sayShorter(MERGE_MAX.title, m.title.length)}`)
      if (typeof m.body !== 'string' || m.body.length > MERGE_MAX.body) problems.push(`output.merge body must be text of at most ${MERGE_MAX.body} characters`)
      if (m.at !== undefined && !isText(m.at)) problems.push('output.merge at must be a time')
      const credit = textCredit(typeof m.title === 'string' ? m.title : '') ?? textCredit(typeof m.body === 'string' ? m.body : '')
      if (credit) problems.push(creditProblem(credit))
    }
  }
  const p = out.pr
  if (p !== undefined) {
    if (!isObject(p)) return [...problems, 'output.pr must be a JSON object']
    if (p.url != null && !(typeof p.url === 'string' && /^https:\/\/\S{1,290}$/.test(p.url))) problems.push('output.pr url must be an https link')
    if (p.number != null && !(Number.isInteger(p.number) && p.number > 0)) problems.push('output.pr number must be a whole number above 0')
    if (p.state != null && !PR_STATES.includes(p.state)) problems.push(`output.pr state must be one of ${PR_STATES.join(', ')}`)
    if (p.checks != null && !CHECKS.includes(p.checks)) problems.push(`output.pr checks must be one of ${CHECKS.join(', ')}`)
    for (const key of ['openedAt', 'checkedAt']) if (p[key] != null && !isText(p[key])) problems.push(`output.pr ${key} must be null or a time`)
    if (p.error != null && !(isText(p.error) && p.error.length <= 300)) problems.push('output.pr error must be null or text of at most 300 characters')
    if (p.pushed !== undefined && typeof p.pushed !== 'boolean') problems.push('output.pr pushed must be true or false')
    if (p.previous != null) {
      // a pull request opened before a send that failed: kept, never shown as the current one
      if (!isObject(p.previous) || !(typeof p.previous.url === 'string' && /^https:\/\/\S{1,290}$/.test(p.previous.url))) problems.push('output.pr previous must be an earlier pull request with an https link')
    }
  }
  return problems
}

/**
 * Ready to send: the agent recorded it, and no pull request stands for that record. One stands
 * while it is open, or, merged or closed, when the record is not newer than it (a `flow pr` after
 * a pull request merged is the next one). A failed send (a pr with an error and no url) opened
 * nothing, so it is ready again.
 */
export function mergeReady(out = {}) {
  if (!isObject(out.merge)) return false
  const pr = out.pr
  if (!pr?.url) return true
  return pr.state !== 'open' && String(out.merge.at || '') > String(pr.openedAt || '')
}
