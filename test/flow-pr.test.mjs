// Tests for Send to the base branch, the data half: the agent-owned `output.merge`
// (flow-merge.mjs, validated in flows.mjs), the server-owned `output.pr` that no
// agent can set (not through `flow write`, not through any CLI command), the
// derived `derived.output.merge.ready`, and the `flow pr` command
// (tools/pr-cli.mjs). FACTORY_DATA_DIR points at a fresh temp folder BEFORE the
// imports, so no test touches the real data/ folder.

import { after, test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
process.env.FACTORY_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'flow-pr-test-'))
const F = await import('../flows.mjs')
const M = await import('../flow-merge.mjs')
const { runFlow } = await import('../tools/flow-cli.mjs')
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'flow-pr-files-'))
after(() => {
  fs.rmSync(F.DATA_DIR, { recursive: true, force: true })
  fs.rmSync(TMP, { recursive: true, force: true })
})

const FIXTURE = JSON.parse(fs.readFileSync(path.join(HERE, 'fixtures', 'no-visual.json'), 'utf8'))
const AT = '2026-11-12T10:00:00Z'
const MERGE = { head: 'feature/dark-mode', base: 'dev', title: 'Add a dark mode to Settings', body: '## What\n\nA moon switch next to Theme.', at: AT }
/** The no-visual fixture with `output` changed by `edit`. */
const fx = (edit = () => {}) => {
  const f = structuredClone(FIXTURE)
  f.output ||= {}
  edit(f.output, f)
  return f
}
const problems = edit => F.validateFlow(fx(edit))
const run = (...argv) => runFlow(argv, { by: 'Agent 3', cwd: TMP })
const write = (name, text) => { fs.writeFileSync(path.join(TMP, name), text); return name }

// ═══ branch names and the credit rule (flow-merge.mjs) ═══

test('a branch name is letters, digits, dots, dashes, underscores and slashes, at most 100, no .., not starting with a dash', () => {
  for (const ok of ['dev', 'main', 'feature/dark-mode', 'release/1.2', 'a_b']) assert.equal(M.isBranch(ok), true, ok)
  for (const bad of ['', '-x', 'a..b', 'a b', 'a:b', '+dev', 'x'.repeat(101), 'dev~1', 'a^', null, 3]) assert.equal(M.isBranch(bad), false, String(bad))
})

test('ONE credit rule: an AI co-author trailer, a Generated with line, or an authorship phrase blocks; nothing else does', () => {
  const blocks = [
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'co-authored-by: Copilot <198982749+Copilot@users.noreply.github.com>',
    'Co-authored-by: Bot <bot@openai.com>',
    '🤖 Generated with [Claude Code](https://example.com)',
    'Generated with a tool',
    '> Generated by a tool',
    'Generated using Claude',
    'Signed-off-by: Claude <noreply@anthropic.com>',
    'Docs generated with Claude Code [Claude Code]',
    'Made in one pass 🤖 generated with a tool',
    'Written by ChatGPT',
    'Built with Copilot',
    'Implemented with the help of nobody, made by Cursor',
  ]
  for (const line of blocks) assert.ok(M.creditOf(line), line)
  const passes = [
    'Gemini 3 Flash summarises the report',
    'regenerated with pnpm',
    'update CLAUDE.md',
    'Co-authored-by: Jane Doe <jane@example.com>',
    'Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>',
    'chore: bump the anthropic client',
    'see Co-Authored-By: Claude in the docs',
    'the cursor moves to the end',
    'The report is generated with every run of the job',
    'The summary is generated by Gemini 3 Flash',
    'Pagination built with a cursor',
    'Docs generated with Gemini',
    'Signed-off-by: Jane Doe <jane@example.com>',
  ]
  for (const line of passes) assert.equal(M.creditOf(line), null, line)
})

test('commitCredits and textCredit use that one rule, line by line', () => {
  assert.deepEqual(M.commitCredits('fix: the theme\n\nCo-Authored-By: Jane Doe <jane@example.com>\n'), [], 'a human co-author passes')
  assert.deepEqual(M.commitCredits('fix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>'), ['Co-Authored-By: Claude <noreply@anthropic.com>'])
  assert.deepEqual(M.commitCredits('chore: bump the anthropic client\n\nsrc/openai/client.ts moved'), [])
  assert.equal(M.textCredit('Add a dark mode'), null)
  assert.equal(M.textCredit('Gemini 3 Flash summarises the report'), null)
  assert.equal(M.textCredit('ok\nBuilt with Claude'), 'Built with Claude')
  assert.equal(M.textCredit('ok\n🤖 Generated with something'), '🤖 Generated with something')
})

test('the blocker names the line and says what to do, for a title or body and for a commit', () => {
  assert.equal(M.creditProblem('Built with Claude'), 'a pull request must not credit an AI tool: "Built with Claude": remove this line')
  const long = `Built with Claude ${'x'.repeat(80)}`
  assert.equal(M.creditProblem(long), `a pull request must not credit an AI tool: "${long.slice(0, 59)}…": remove this line`)
  assert.equal(M.commitProblem('abc1234', 'Co-Authored-By: Claude <noreply@anthropic.com>'),
    'Commit abc1234 "Co-Authored-By: Claude <noreply@anthropic.com>": this commit credits an AI tool; it cannot be reworded once pushed, so make a new branch without it')
})

// ═══ validation of output.merge ═══

test('a good merge is valid', () => {
  assert.deepEqual(problems(o => { o.merge = { ...MERGE } }), [])
})

test('merge: bad branch names, a missing or long title, a title on two lines, a long body are each one plain problem', () => {
  const p = problems(o => { o.merge = { ...MERGE, head: '-x', base: 'a..b', title: '', body: 'x'.repeat(6001) } })
  assert.equal(p.length, 4, p.join('\n'))
  assert.ok(p.some(l => /output\.merge head must be a branch name/.test(l)))
  assert.ok(p.some(l => /output\.merge base must be a branch name/.test(l)))
  assert.ok(p.some(l => /output\.merge title must say what the pull request does/.test(l)))
  assert.ok(p.some(l => /output\.merge body must be text of at most 6000 characters/.test(l)))
  assert.match(problems(o => { o.merge = { ...MERGE, title: 'x'.repeat(121) } }).join(), /title: .*120/)
  assert.match(problems(o => { o.merge = { ...MERGE, title: 'one\ntwo' } }).join(), /title must be one line/)
  assert.match(problems(o => { o.merge = 'x' }).join(), /output\.merge must be a JSON object/)
})

test('merge: a title or body that credits an AI tool is refused with the plain message', () => {
  assert.deepEqual(problems(o => { o.merge = { ...MERGE, title: 'Dark mode, built with Claude' } }),
    ['a pull request must not credit an AI tool: "Dark mode, built with Claude": remove this line'])
  assert.deepEqual(problems(o => { o.merge = { ...MERGE, body: 'Done.\n\nCo-Authored-By: Claude <noreply@anthropic.com>' } }),
    ['a pull request must not credit an AI tool: "Co-Authored-By: Claude <noreply@anthropic.com>": remove this line'])
  assert.deepEqual(problems(o => { o.merge = { ...MERGE, title: 'Gemini 3 Flash summarises the report', body: 'Co-authored-by: Jane Doe <jane@example.com>' } }), [], 'a product name or a human co-author passes')
})

test('pr: the server shape is valid; a bad state, checks, url or error is a problem', () => {
  const PR = { url: 'https://example.com/acme/app/pull/12', number: 12, state: 'open', openedAt: AT, checks: 'passing', checkedAt: AT, error: null }
  assert.deepEqual(problems(o => { o.pr = { ...PR } }), [])
  assert.deepEqual(problems(o => { o.pr = { error: 'The push was refused.' } }), [], 'a failed send stores the error alone')
  const p = problems(o => { o.pr = { ...PR, state: 'gone', checks: 'green', url: 'http://x/pull/1', number: -1 } })
  assert.equal(p.length, 4, p.join('\n'))
})

// ═══ server-owned pr: never from an agent ═══

test('flow write never sets pr: an agent pr is dropped, the stored one is kept, even with "output": {}', () => {
  const stored = fx(o => { o.pr = { url: 'https://example.com/acme/app/pull/3', number: 3, state: 'open', openedAt: AT, checks: 'pending', checkedAt: null, error: null } })
  const forged = fx(o => { o.pr = { url: 'https://example.com/acme/app/pull/99', number: 99, state: 'merged', openedAt: AT, checks: 'passing', checkedAt: AT, error: null } })
  assert.equal(F.mergeKeepingAnswers(forged, stored).output.pr.number, 3)
  const none = fx(o => { o.pr = { error: 'forged' } })
  assert.equal(F.mergeKeepingAnswers(none, fx()).output.pr, undefined, 'no stored pr: the agent one is dropped')
  const cleared = fx()
  cleared.output = {}
  assert.equal(F.mergeKeepingAnswers(cleared, stored).output.pr.number, 3)
  assert.ok(F.SERVER_OUTPUT.includes('pr'))
})

test('derived.output.merge.ready: set and not sent, or sent and failed, or a newer record after the PR closed', () => {
  const ready = edit => F.derive(fx(edit)).output.merge.ready
  assert.equal(ready(() => {}), false, 'nothing recorded')
  assert.equal(ready(o => { o.merge = { ...MERGE } }), true)
  assert.equal(ready(o => { o.merge = { ...MERGE }; o.pr = { error: 'The push was refused.' } }), true, 'nothing was opened: try again')
  const open = { url: 'https://example.com/acme/app/pull/3', number: 3, state: 'open', openedAt: '2026-11-12T11:00:00Z', checks: 'pending', checkedAt: null, error: null }
  assert.equal(ready(o => { o.merge = { ...MERGE }; o.pr = { ...open } }), false, 'a PR is open')
  assert.equal(ready(o => { o.merge = { ...MERGE, at: '2026-11-12T12:00:00Z' }; o.pr = { ...open } }), false, 'still open: not again')
  assert.equal(ready(o => { o.merge = { ...MERGE, at: '2026-11-12T12:00:00Z' }; o.pr = { ...open, state: 'merged' } }), true, 'recorded again after it merged')
  assert.equal(ready(o => { o.merge = { ...MERGE }; o.pr = { ...open, state: 'merged' } }), false, 'the record it was sent from')
})

// ═══ flow pr (tools/pr-cli.mjs) ═══

test('flow pr records the merge from the body file, needs --by, and flow show says it is not sent', () => {
  F.writeFlow(fx())
  const body = write('body.md', '﻿## What\r\n\r\nA moon switch.\r\n')
  assert.deepEqual(runFlow(['pr', FIXTURE.id, '--head', 'feature/dark-mode', '--base', 'dev', '--title', 'Add a dark mode', '--body-file', body], { cwd: TMP }).code, 1)
  const r = run('pr', FIXTURE.id, '--head', 'feature/dark-mode', '--base', 'dev', '--title', 'Add a dark mode', '--body-file', body)
  assert.equal(r.code, 0, r.out)
  const merge = F.readFlow(FIXTURE.id).output.merge
  assert.deepEqual({ ...merge, at: 'x' }, { head: 'feature/dark-mode', base: 'dev', title: 'Add a dark mode', body: '## What\n\nA moon switch.\n', at: 'x' })
  assert.match(run('show', FIXTURE.id).err, /send: feature\/dark-mode -> dev, not sent/)
})

test('flow pr refuses a missing flag, an unreadable file, a bad branch, and a credit line, writing nothing', () => {
  const body = write('ok.md', 'Fine.')
  const before = JSON.stringify(F.readFlow(FIXTURE.id).output.merge)
  assert.match(run('pr', FIXTURE.id, '--head', 'feature/x', '--base', 'dev', '--title', 'T').out, /--body-file/)
  assert.match(run('pr', FIXTURE.id, '--head', 'feature/x', '--base', 'dev', '--title', 'T', '--body-file', 'missing.md').out, /Cannot read/)
  assert.match(run('pr', FIXTURE.id, '--head', '-x', '--base', 'dev', '--title', 'T', '--body-file', body).out, /head must be a branch name/)
  const credit = write('credit.md', 'Done.\nCo-Authored-By: Claude <noreply@anthropic.com>')
  const r = run('pr', FIXTURE.id, '--head', 'feature/x', '--base', 'dev', '--title', 'T', '--body-file', credit)
  assert.equal(r.code, 1)
  assert.equal(r.out, 'a pull request must not credit an AI tool: "Co-Authored-By: Claude <noreply@anthropic.com>": remove this line')
  assert.equal(JSON.stringify(F.readFlow(FIXTURE.id).output.merge), before)
})

test('no CLI command takes a pr: flow pr has no flag for it, and --clear removes only the merge', () => {
  const f = F.readFlow(FIXTURE.id)
  f.output.pr = { url: 'https://example.com/acme/app/pull/5', number: 5, state: 'open', openedAt: AT, checks: 'failing', checkedAt: AT, error: null }
  F.writeFlow(f)
  assert.match(run('show', FIXTURE.id).err, /send: PR #5 open, checks failing/)
  assert.equal(run('pr', FIXTURE.id, '--clear').code, 0)
  const now = F.readFlow(FIXTURE.id).output
  assert.equal(now.merge, undefined)
  assert.equal(now.pr.number, 5, 'the server record stays')
  assert.match(run('pr', FIXTURE.id, '--clear', '--head', 'x').out, /not both/)
})

